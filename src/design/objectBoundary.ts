/**
 * 목적어 명사구가 어디서 시작하는가 — 형태소 분석기 없이.
 *
 * 여기까지 오기 전에는 동사 앞 **두 어절**을 목적어로 잡았다. 그 폭이 옳은지는
 * 우리 말뭉치 안에서만 다퉜고, 말뭉치는 우리가 쓴 것이다. KLUE-DP 검증셋 2,000문장
 * (남이 쓴 문장에 남이 붙인 의존 트리)에 같은 질문을 물어 보니 답이 분명했다:
 *
 *     목적어구 1,691개 · 연속 100.0%
 *     길이   1어절 39.1% · 2어절 이하 63.6% · 3어절 이상 36.4%
 *     고정 2어절 창  정확 27.6% · 잘림 36.4% · 과잉 36.0%
 *
 * 폭을 바꿔서 될 일이 아니다. 1어절은 39.1%, 3어절은 18.6%이고, 고정 폭은 어느
 * 값이든 양쪽으로 함께 틀린다. 남는 질문은 **어절 하나를 보고 그것이 목적어구
 * 안인지 밖인지 말할 수 있는가** 였고, 같은 데이터가 그 답도 준다 — 마지막
 * 형태소의 품사가 거의 결정한다:
 *
 *     안으로 잇는 것   NNP 100% · 관형격 `의` 99.6% · 관형형 어미 99.5% ·
 *                     관형사 98% · 일반명사 91.5% · 접속조사 88.3%
 *     밖에서 끊는 것   보조사 `는/도/만` 12.1% · 연결어미 19.3% ·
 *                     부사격 `에/로` 36.6% · 부사 38.0% · 주격 `이/가` 38.3%
 *
 * 품사 태그로 이 규칙을 쓰면 정확 69.4%. 우리에게는 분석기가 없고 앞으로도 없을
 * 것이므로(설계 단계는 오프라인이고 의존성을 늘릴 자리가 아니다) 쓸 수 있는 것은
 * 표면형뿐인데, 표면형만으로도 **정확 47.1% · 잘림 18.7% · 과잉 34.1%** 로 고정
 * 폭보다 세 축 모두 낫다. 재현은 `scripts/measureEdgeRule.mjs`.
 *
 * ## `는` 이 유일한 갈림길이다
 *
 * "탐지하**는**" 은 관형형 어미라 구 안이고 "필드**는**" 은 보조사라 밖인데
 * 마지막 글자가 같다. 형태소를 모르면 앞 음절로 가르는 수밖에 없고, 그래서
 * `ADNOMINAL` 은 열린 목록이다 — 빠진 활용형은 그 어절에서 구를 끊고, 결과는
 * 예전 동작인 "덜 보여주기" 로 떨어진다. 잘리는 쪽이 넘치는 쪽보다 낫다는 것이
 * 이 모듈의 기본값이다.
 */

/** 주격·보조사. 여기서 끊는다 — 앞은 다른 성분이다. */
const STOP_PARTICLE = /(?:이|가|께서|은|는|도|만|밖에|조차|마저)$/;

/** 부사격. "결론에", "서버로", "어제부터" — 어디서·무엇으로이지 무엇이 아니다. */
const ADVERBIAL = /(?:에서|에게|에|으로|로|부터|까지|보다|처럼|만큼|대로|한테)$/;

/** 관형격 `의`. "행정 정보 시스템**의** 접근 권한 모델" 은 한 덩어리다. */
const GENITIVE = /의$/;

/** 접속조사. 나열은 하나의 명사구다 — `COORDINATOR` 와 같은 판단. */
const CONJUNCTION = /(?:와|과|랑|이랑|하고)$/;

/**
 * 관형형 어미가 붙은 용언.
 *
 * 열린 목록이고 그래야 한다. `-는` 은 보조사와 글자가 같으므로 "용언 어간 + 는"
 * 을 전부 알아보려면 어휘가 필요하고, 어휘 없이 넓게 잡으면 "필드는" 이 구 안으로
 * 들어온다. 그래서 흔한 활용형만 적고, 빠진 것은 그 자리에서 구를 끊는다.
 */
const ADNOMINAL =
  /(?:하는|되는|있는|없는|보는|받는|주는|쓰는|나는|가는|오는|드는|잡는|찾는|만드는|이루는|맞는|넘는|따르는|남는)$|(?:된|한|인|같은|아닌|많은|적은|만든|남은|붙은|빠진|걸린|늘어난|줄어든|다른|새로운|어긋나는)$|(?:할|될|볼|줄|쓸)$/;

/** 목적어구에 이어 붙는 어절인가. */
export function joinsPhrase(token: string): boolean {
  const w = token.replace(/[.,!?"'()“”‘’]/g, "").trim();
  if (w.length === 0) return false;
  // 순서가 중요하다. `-는` 은 보조사 검사보다 먼저 봐야 "탐지하는" 이 "필드는" 과
  // 같은 취급을 받지 않는다.
  if (ADNOMINAL.test(w) || GENITIVE.test(w)) return true;
  if (STOP_PARTICLE.test(w) || ADVERBIAL.test(w)) return false;
  if (CONJUNCTION.test(w)) return true;
  // 조사가 없는 맨 명사. 합성 명사구의 구성원이다 — "창고 입출고 로그".
  return true;
}

/**
 * 머리에서 왼쪽으로 걸어가 목적어구가 시작하는 자리를 찾는다.
 *
 * `units` 는 이미 절 경계와 문법 토큰으로 걸러진 열이고, 마지막 항목이 머리다.
 */
export function objectStart(units: readonly string[]): number {
  let start = units.length - 1;
  while (start - 1 >= 0 && joinsPhrase(units[start - 1] ?? "")) start -= 1;
  return Math.max(0, start);
}
